export type ErrorCode = keyof typeof ERRORS;

/** 仅前端使用的错误码 */
export type ClientErrorCode = 'NETWORK_ERROR';

/** 没有具体错误码时按 HTTP 状态归类 */
export function errorCodeForStatus(status: number): ErrorCode {
  const map: Record<number, ErrorCode> = { 400: 'BAD_REQUEST', 401: 'AUTH_REQUIRED', 403: 'FORBIDDEN', 404: 'NOT_FOUND', 409: 'CONFLICT', 413: 'FILE_TOO_LARGE' };
  return map[status] ?? (status >= 500 ? 'INTERNAL_ERROR' : 'BAD_REQUEST');
}

/** API 错误响应体 */
export interface ApiErrorBody {
  statusCode: number;
  code: ErrorCode;
  message: string;
  params?: Record<string, string | number>;
  [extra: string]: unknown;
}
